// i18n — minimal in-bundle translation table for weft-loom UI text.
//
// Why hand-rolled instead of svelte-i18n / svelte-intl :
//   - 7 locales × ~80 strings = trivial size — keeping it in-bundle
//     avoids one more fetch + the loader complexity of code-split
//     locale files.
//   - Translation lookup is a $derived getter ; every consumer that
//     wraps a string in `t('foo.bar')` automatically rerenders on
//     locale change without per-component subscriptions.
//
// Add a string : (1) put it in `dict.en` with a stable key like
// `menubar.run`, (2) translate it in each of the other locales —
// missing keys fall back to English so the UI doesn't go blank.

