// Detect the browser language ; fallback to `en` for anything we
// don't ship a dictionary for. Honour the `weft-loom-locale` key in
// localStorage so the user's choice persists across reloads.
function detect(): Locale {
  try {
    const stored = localStorage.getItem('weft-loom-locale') as Locale | null;
    if (stored && stored in dict) return stored;
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    if (nav in dict) return nav as Locale;
  } catch {
    /* SSR / hostile env */
  }
  return 'en';
}

// `current` is a $state-backed reactive. Svelte components import
// `i18n` then read `i18n.current` ; the t() helper closes over it
// so every consumer rerenders on a switch.
class I18n {
  current = $state<Locale>(detect());
  set(locale: Locale) {
    this.current = locale;
    try { localStorage.setItem('weft-loom-locale', locale); } catch { /* ignore */ }
  }
  t(key: string): string {
    return dict[this.current][key] ?? dict.en[key] ?? key;
  }
}

export const i18n = new I18n();
export function t(key: string): string { return i18n.t(key); }
